def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def scientific_digest(manifest: dict) -> str:
    profile = {key: manifest[key] for key in SCIENTIFIC_FIELDS}
    return hashlib.sha256(json.dumps(profile, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()


def code_identity() -> dict[str, str]:
    paths = list((ROOT / "src").rglob("*.py")) + [
        ROOT / "scripts" / name for name in (
            "evaluate_simon_confirmation.py", "generate_simon_confirmation_dataset.py",
            "analyze_simon_confirmation.py", "run_neural_ranking_worker.py",
            "audit_simon_training_key_replay.py",
        )
    ]
    paths.append(ROOT / "tests/fixtures/simon_reference_oracle.py")
    return {str(path.relative_to(ROOT)): digest(path) for path in sorted(paths)}


def distribution_artifact_identity(names: tuple[str, ...]) -> dict[str, str]:
    """Pin installed package code/native libraries; exclude generated bytecode."""
    result = {}
    for name in names:
        distribution = importlib.metadata.distribution(name)
        identity = hashlib.sha256()
        for relative in sorted(distribution.files or [], key=str):
            if str(relative).endswith((".pyc", ".pyo")):
                continue
            path = distribution.locate_file(relative)
            if not path.is_file():
                raise ValueError(f"Missing installed runtime artifact: {name}/{relative}")
            identity.update(str(relative).encode() + b"\0" + digest(path).encode() + b"\n")
        result[name] = identity.hexdigest()
    return result


def local_runtime_identity() -> dict:
    import pycryptosat
    import torch

    packages = sorted((d.metadata["Name"], d.version) for d in importlib.metadata.distributions())
    return {
        "python_executable": sys.executable,
        "python_realpath": str(Path(sys.executable).resolve()),
        "python_sha256": digest(Path(sys.executable)),
        "python_version": sys.version,
        "platform": platform.platform(), "machine": platform.machine(),
        "packages": [list(pair) for pair in packages],
        "numeric_package_artifacts": distribution_artifact_identity(("numpy", "torch")),
        "pycryptosat_module": pycryptosat.__file__,
        "pycryptosat_sha256": digest(Path(pycryptosat.__file__)),
        "pytorch_threads": {"intra_op": torch.get_num_threads(), "inter_op": torch.get_num_interop_threads()},
        "thread_environment": {key: os.environ.get(key) for key in THREAD_ENVIRONMENT},
    }


def tensorflow_runtime_identity(python: Path) -> dict:
    # An interpreter/environment probe only. No checkpoint, data, inference or SAT.
    script = """import hashlib, importlib.metadata, json, pathlib, platform, sys
sys.path.insert(0, sys.argv[1])
from neural_sat_speck.simon.confirmation_profile import distribution_artifact_identity
def sha(p): return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()
print(json.dumps({'python_executable':sys.executable,'python_realpath':str(pathlib.Path(sys.executable).resolve()),
'python_sha256':sha(sys.executable),'python_version':sys.version,'platform':platform.platform(),
'packages':sorted((d.metadata['Name'],d.version) for d in importlib.metadata.distributions()),
'numeric_package_artifacts':distribution_artifact_identity(('numpy','tensorflow','keras','h5py'))}))
"""
    result = subprocess.run([str(python), "-c", script, str(ROOT / "src")], check=True, capture_output=True, text=True, timeout=30)
    return json.loads(result.stdout)


def verify_execution_pins(manifest: dict, *, tensorflow_python: Path) -> None:
    pins = manifest.get("execution_pins", {})
    if pins.get("source_sha256") != code_identity():
        raise ValueError("Executed source identity is missing or has drifted")
    if pins.get("python_runtime") != local_runtime_identity():
        raise ValueError("Python runtime/environment identity is missing or has drifted")
    if pins.get("tensorflow_runtime") != tensorflow_runtime_identity(tensorflow_python):
        raise ValueError("TensorFlow interpreter/environment identity is missing or has drifted")
    if any(os.environ.get(key) != value for key, value in THREAD_ENVIRONMENT.items()):
        raise ValueError("Confirmation numeric/thread environment differs from frozen policy")
